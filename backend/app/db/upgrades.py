def _jsonb_payload(value: object) -> object:
    if isinstance(value, str):
        return cast(object, json.loads(value))
    return value


def _bundled_package_preset_needs_reseed(
    connection: Connection,
    *,
    package_key: str,
    manifest_hash: str,
    compiled_hash: str,
) -> bool:
    row = (
        connection.execute(
            text(
                """
                SELECT manifest_source, manifest_hash, package_definition,
                       compiled_plan, compiled_hash
                FROM workflow_packages
                WHERE key = :package_key
                """
            ),
            {"package_key": package_key},
        )
        .mappings()
        .one_or_none()
    )
    if row is None:
        return True

    if row["manifest_hash"] != manifest_hash or row["compiled_hash"] != compiled_hash:
        return True

    try:
        package_definition = _jsonb_payload(row["package_definition"])
        WorkflowPackageManifest.model_validate(package_definition)
    except (TypeError, ValueError, ValidationError):
        return True

    return False



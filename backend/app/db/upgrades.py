def _backfill_agent_model_connections(
    engine: Engine,
    table_names: set[str],
) -> None:
    if not {"agents", "model_connections"} <= table_names:
        return

    inspector = inspect(engine)
    agent_columns = {column["name"]: column for column in inspector.get_columns("agents")}
    if "model_connection_id" not in agent_columns or "model" not in agent_columns:
        return

    needs_non_null_enforcement = bool(agent_columns["model_connection_id"].get("nullable", True))

    with engine.begin() as connection:
        unresolved_agent_count = connection.execute(
            text("SELECT COUNT(*) FROM agents WHERE model_connection_id IS NULL")
        ).scalar_one()
        if unresolved_agent_count == 0:
            if needs_non_null_enforcement:
                connection.exec_driver_sql(
                    "ALTER TABLE agents ALTER COLUMN model_connection_id SET NOT NULL"
                )
            return

        legacy_models = connection.execute(
            text(
                "SELECT DISTINCT BTRIM(model) AS model_id "
                "FROM agents "
                "WHERE model_connection_id IS NULL AND model IS NOT NULL AND BTRIM(model) <> '' "
                "ORDER BY model_id"
            )
        ).scalars()

        for legacy_model in legacy_models:
            placeholder_parameters = {
                "base_url": _MODEL_CONNECTION_PLACEHOLDER_BASE_URL,
                "model_id": legacy_model,
                "name": legacy_model,
                "reasoning_effort": _MODEL_CONNECTION_PLACEHOLDER_REASONING_EFFORT,
                "timeout_seconds": _MODEL_CONNECTION_PLACEHOLDER_TIMEOUT_SECONDS,
            }
            placeholder_connection_id = connection.execute(
                text(
                    "SELECT id FROM model_connections "
                    "WHERE status = 'active' "
                    "AND name = :name "
                    "AND model_id = :model_id "
                    "AND base_url = :base_url "
                    "AND reasoning_effort = :reasoning_effort "
                    "AND timeout_seconds = :timeout_seconds "
                    "AND has_api_key = FALSE "
                    "ORDER BY id LIMIT 1"
                ),
                placeholder_parameters,
            ).scalar_one_or_none()

            if placeholder_connection_id is None:
                placeholder_connection_id = connection.execute(
                    text(
                        "INSERT INTO model_connections ("
                        "status, name, description, base_url, organization, project, model_id, "
                        "reasoning_effort, timeout_seconds, secret_payload, has_api_key, "
                        "created_at, updated_at"
                        ") VALUES ("
                        "'active', :name, '', :base_url, NULL, NULL, :model_id, "
                        ":reasoning_effort, :timeout_seconds, '{}'::jsonb, FALSE, NOW(), NOW()"
                        ") RETURNING id"
                    ),
                    placeholder_parameters,
                ).scalar_one()

            connection.execute(
                text(
                    "UPDATE agents "
                    "SET model_connection_id = :model_connection_id, updated_at = NOW() "
                    "WHERE model_connection_id IS NULL AND BTRIM(model) = :legacy_model"
                ),
                {
                    "legacy_model": legacy_model,
                    "model_connection_id": placeholder_connection_id,
                },
            )

        remaining_null_count = connection.execute(
            text("SELECT COUNT(*) FROM agents WHERE model_connection_id IS NULL")
        ).scalar_one()
        if needs_non_null_enforcement and remaining_null_count == 0:
            connection.exec_driver_sql(
                "ALTER TABLE agents ALTER COLUMN model_connection_id SET NOT NULL"
            )


def _recover_stale_agent_platform_runs(engine: Engine, table_names: set[str]) -> None:
    if "runs" not in table_names:
        return

    with engine.begin() as connection:
        connection.execute(
            text(
                """
                UPDATE runs
                SET status = 'failed',
                    error = COALESCE(NULLIF(error, ''), :restart_failure_message),
                    finished_at = COALESCE(finished_at, NOW()),
                    updated_at = NOW()
                WHERE status = 'running'
                """
            ),
            {"restart_failure_message": _AGENT_PLATFORM_RESTART_FAILURE_MESSAGE},
        )


def _ensure_run_target_identity_support(engine: Engine, table_names: set[str]) -> None:
    if "runs" not in table_names:
        return

    inspector = inspect(engine)
    run_columns = {column["name"] for column in inspector.get_columns("runs")}
    run_constraints = {
        constraint["name"]
        for constraint in inspector.get_check_constraints("runs")
        if constraint.get("name")
    }

    with engine.begin() as connection:
        if "target_kind" not in run_columns:
            connection.exec_driver_sql("ALTER TABLE runs ADD COLUMN target_kind VARCHAR(20)")

        has_workflow_id = "workflow_id" in run_columns
        has_workflow_key = "workflow_key" in run_columns
        has_workflow_version = "workflow_version" in run_columns
        has_target_id = "target_id" in run_columns
        has_target_key = "target_key" in run_columns
        has_target_version = "target_version" in run_columns
        has_target_kind = "target_kind" in run_columns

        if has_workflow_id and has_target_id:
            target_id_conflicts = connection.execute(
                text(
                    "SELECT COUNT(*) FROM runs "
                    "WHERE workflow_id IS NOT NULL AND target_id IS NOT NULL "
                    "AND workflow_id <> target_id"
                )
            ).scalar_one()
            if target_id_conflicts:
                raise RuntimeError(_RUN_TARGET_IDENTITY_CONFLICT_MESSAGE)

        if has_workflow_key and has_target_key:
            target_key_conflicts = connection.execute(
                text(
                    "SELECT COUNT(*) FROM runs "
                    "WHERE workflow_key IS NOT NULL AND target_key IS NOT NULL "
                    "AND workflow_key <> target_key"
                )
            ).scalar_one()
            if target_key_conflicts:
                raise RuntimeError(_RUN_TARGET_IDENTITY_CONFLICT_MESSAGE)

        if has_workflow_version and has_target_version:
            target_version_conflicts = connection.execute(
                text(
                    "SELECT COUNT(*) FROM runs "
                    "WHERE workflow_version IS NOT NULL AND target_version IS NOT NULL "
                    "AND workflow_version <> target_version"
                )
            ).scalar_one()
            if target_version_conflicts:
                raise RuntimeError(_RUN_TARGET_IDENTITY_CONFLICT_MESSAGE)

        if (
            has_workflow_id
            and has_target_id
            and has_workflow_key
            and has_target_key
            and has_workflow_version
            and has_target_version
            and has_target_kind
        ):
            target_kind_conflicts = connection.execute(
                text(
                    "SELECT COUNT(*) FROM runs "
                    "WHERE workflow_id IS NOT NULL AND workflow_key IS NOT NULL "
                    "AND workflow_version IS NOT NULL AND target_kind IS NOT NULL "
                    "AND BTRIM(target_kind) <> '' AND target_kind <> 'workflow'"
                )
            ).scalar_one()
            if target_kind_conflicts:
                raise RuntimeError(_RUN_TARGET_IDENTITY_CONFLICT_MESSAGE)

        if "workflow_id" in run_columns and "target_id" not in run_columns:
            connection.exec_driver_sql("ALTER TABLE runs RENAME COLUMN workflow_id TO target_id")
        elif "workflow_id" in run_columns and "target_id" in run_columns:
            connection.exec_driver_sql(
                "UPDATE runs SET target_id = workflow_id WHERE target_id IS NULL"
            )
            connection.exec_driver_sql("ALTER TABLE runs DROP COLUMN workflow_id")

        if "workflow_key" in run_columns and "target_key" not in run_columns:
            connection.exec_driver_sql("ALTER TABLE runs RENAME COLUMN workflow_key TO target_key")
        elif "workflow_key" in run_columns and "target_key" in run_columns:
            connection.exec_driver_sql(
                "UPDATE runs SET target_key = workflow_key WHERE target_key IS NULL"
            )
            connection.exec_driver_sql("ALTER TABLE runs DROP COLUMN workflow_key")

        if "workflow_version" in run_columns and "target_version" not in run_columns:
            connection.exec_driver_sql(
                "ALTER TABLE runs RENAME COLUMN workflow_version TO target_version"
            )
        elif "workflow_version" in run_columns and "target_version" in run_columns:
            connection.exec_driver_sql(
                "UPDATE runs SET target_version = workflow_version WHERE target_version IS NULL"
            )
            connection.exec_driver_sql("ALTER TABLE runs DROP COLUMN workflow_version")

        connection.exec_driver_sql(
            "UPDATE runs "
            "SET target_kind = 'workflow' "
            "WHERE target_kind IS NULL OR BTRIM(target_kind) = ''"
        )
        connection.exec_driver_sql("ALTER TABLE runs ALTER COLUMN target_kind SET NOT NULL")
        connection.exec_driver_sql("ALTER TABLE runs ALTER COLUMN target_id SET NOT NULL")
        connection.exec_driver_sql("ALTER TABLE runs ALTER COLUMN target_key SET NOT NULL")
        connection.exec_driver_sql("ALTER TABLE runs ALTER COLUMN target_version SET NOT NULL")


def _ensure_bundled_package_preset_row(
    connection: Connection,
    *,
    sql_file: str,
    package_key: str,
    manifest_hash: str,
    compiled_hash: str,
) -> None:
    preset_sql_path = _preset_package_sql_path(sql_file)
    if not preset_sql_path.exists():
        return

    if _bundled_package_preset_needs_reseed(
        connection,
        package_key=package_key,
        manifest_hash=manifest_hash,
        compiled_hash=compiled_hash,
    ):
        _ = connection.execute(
            text("DELETE FROM workflow_packages WHERE key = :package_key"),
            {"package_key": package_key},
        )
        _insert_bundled_package_preset(connection, preset_sql_path)


